def build_section(v3: dict) -> dict:
    chain = hash_chain(chain_bodies(), v3["genesis_prev_hash"])
    artifacts = [
        {"name": name, "ref": artifact_ref(obj), "object": obj, "canonical": canon(obj)}
        for name, obj in ARTIFACTS.items()
    ]
    return {
        "spec": "docs/specs/journal.md v0.5 §9.1 (DEC-177)",
        "stream_id": STREAM,
        "artifacts": artifacts,
        "chain": chain,
        "derivation": DERIVATION,
        "invalid_drafts": invalid_drafts(),
    }


class Dumper(yaml.SafeDumper):
    pass


def split_file(text: str) -> tuple[str, str | None]:
    head, found, tail = text.partition(MARKER + "\n")
    return (head, tail) if found else (text, None)


def render(v3_text: str, section: dict) -> str:
    head, _ = split_file(v3_text)
    body = yaml.dump(
        {"agent_stream": section},
        Dumper=Dumper,
        sort_keys=False,
        allow_unicode=True,
        width=10**6,
        default_flow_style=False,
    )
    return head.rstrip("\n") + "\n" + MARKER + "\n" + body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if journal.yaml is not what this generates")
    mode.add_argument("--write", action="store_true", help="rewrite the agent_stream section (the default)")
    parser.add_argument("--vectors", type=Path, default=VECTORS, help="the journal.yaml to read or write")
    args = parser.parse_args(argv)
    vectors: Path = args.vectors

    text = vectors.read_text(encoding="utf-8")
    v3 = yaml.safe_load(split_file(text)[0])
    self_test(v3)
    section = build_section(v3)

    problems = check_chain(section, v3)
    problems += run_mutants(section, v3)
    for problem in problems:
        print(f"FAIL {problem}", file=sys.stderr)
    if problems:
        return 1

    rendered = render(text, section)
    reread = yaml.safe_load(rendered)["agent_stream"]
    if check_chain(reread, v3):
        print("FAIL the rendered YAML does not read back to the same vectors", file=sys.stderr)
        return 1
    if args.check:
        if rendered != text:
            print(f"FAIL {vectors} differs; run reference/journal/generate.py", file=sys.stderr)
            return 1
    else:
        vectors.write_text(rendered, encoding="utf-8")
    print(
        f"ok: v3 vectors reproduced; {len(section['chain'])} agent-stream events, "
        f"{len(section['invalid_drafts'])} invalid drafts, {len(VALIDATOR_MUTANTS)} validator and "
        f"{len(vector_mutants(section))} vector mutants caught"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
