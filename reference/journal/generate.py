def dec(text: str) -> Decimal:
    return Decimal(text)


def round12(value: Decimal) -> str:
    with localcontext() as ctx:
        ctx.prec = 60
        return normalize_decimal(str(value.quantize(Decimal("1e-12"), rounding=ROUND_HALF_EVEN)))


def recompute_decision(chain: list[dict], artifacts: list[dict], d: dict) -> dict:
    """Mandate spec §8.3 from the journaled outputs, the observed quote, and the illustrative inputs,
    computed without the vector's own numbers: the members `DecisionMade` must carry."""
    now = parse_instant(d["now"])[0]
    observation = next(e["body"]["payload"] for e in chain if e["event_type"] == "ObservationRecorded")
    quote = next(a["object"] for a in artifacts if a["ref"] == observation["data_ref"])
    ask = dec(quote["ask"])
    outputs = {e["body"]["payload"]["model_id"]: e for e in chain if e["event_type"] == "ModelOutputRecorded"}
    weights = {m["model_id"]: dec(m["weight"]) for m in d["models"]}
    total = sum(weights.values())
    fresh, missing = {}, Decimal(0)
    for model in d["models"]:
        entry = outputs.get(model["model_id"])
        if entry is None:
            missing += weights[model["model_id"]]
            continue
        p = entry["body"]["payload"]
        as_of, expires = parse_instant(p["as_of"])[0], parse_instant(p["expires_at"])[0]
        if as_of <= now < expires and (now - as_of).total_seconds() <= model["max_output_age_s"]:
            fresh[model["model_id"]] = (entry["body"]["event_id"], p)
        else:
            missing += weights[model["model_id"]]
    f = sum(weights[m] * dec(p["conviction"]) * dec(p["confidence"]) for m, (_, p) in fresh.items())
    score = sum(weights[m] * dec(p["confidence"]) for m, (_, p) in fresh.items())
    exit_c, buy_c = f / total, (f - missing) / total
    assert exit_c > -dec(d["exit_threshold"]), "the vector is an entry, not an exit"
    assert buy_c >= dec(d["entry_threshold"]), "the vector must clear the entry threshold"
    cap = min(dec(d["max_position_usd"]), dec(d["max_position_fraction"]) * dec(d["equity"]))
    target = buy_c * cap * dec(d["size_factor"])
    held = dec(d["market_value"]) + dec(d["working_opening_cost"])
    delta = target - held
    band = dec(d["rebalance_band"]) * cap
    assert delta > 0 and delta >= band, "the vector must not hold"
    bounds = [
        ("max_order_usd", dec(d["max_order_usd"])),
        ("position_cap", cap - held),
        (
            "gross_exposure_cap",
            min(dec(d["max_gross_exposure_usd"]), dec(d["equity"])) - dec(d["gross_exposure"]),
        ),
    ]
    value, clips = delta, []
    for name, bound in bounds:
        if bound < value:
            value, clips = bound, [*clips, name]
    assert value >= band, "the clipped value must not fall below the band"
    step = dec(d["increment"])
    qty = (value / ask / step).to_integral_value(rounding=ROUND_DOWN) * step
    assert qty >= dec(d["min_order_qty"])
    return {
        "instrument_id": next(iter(fresh.values()))[1]["instrument_id"],
        "side": "buy",
        "type": "limit",
        "tif": d["tif"],
        "qty": normalize_decimal(str(qty)),
        "limit_price": normalize_decimal(quote["ask"]),
        "purpose": "open" if held == 0 else "increase",
        "exit_conviction": round12(exit_c),
        "buy_conviction": round12(buy_c),
        "combined_score": round12(score / total),
        "outputs_used": sorted(event_id for event_id, _ in fresh.values()),
        "model_weights": [{"key": k, "value": normalize_decimal(str(weights[k]))} for k in sorted(weights)],
        "clips_applied": clips,
        "dry_run": d["dry_run"],
        "reason_code": None,
        "autonomy": d["autonomy"],
    }


def check_chain(section: dict, v3: dict) -> list[str]:
    """Cross-event facts no single draft check can see. Returns every failure, so seeded bugs can be
    shown to be caught."""
    problems = []
    chain = section["chain"]
    by_type = {e["event_type"]: e["body"] for e in chain}
    prev = v3["genesis_prev_hash"]
    for i, entry in enumerate(chain, start=1):
        body = entry["body"]
        if body["seq"] != i or entry["seq"] != i:
            problems.append(f"seq {i}: gap")
        if body["prev_hash"] != prev:
            problems.append(f"seq {i}: prev_hash does not chain")
        if canon(body) != entry["canonical"]:
            problems.append(f"seq {i}: canonical differs")
        if sha256_hex(entry["canonical"].encode()) != entry["hash"]:
            problems.append(f"seq {i}: hash differs")
        prev = entry["hash"]
        if body["stream_id"] != STREAM or body["event_type"] != entry["event_type"]:
            problems.append(f"seq {i}: stream or type differs")
    stored = {a["ref"]: a for a in section["artifacts"]}
    for a in section["artifacts"]:
        if (
            canon(a["object"]) != a["canonical"]
            or "sha256:" + sha256_hex(a["canonical"].encode()) != a["ref"]
        ):
            problems.append(f"artifact {a['name']}: does not re-hash")
    for entry in chain:
        for ref in entry["body"]["artifact_refs"]:
            if ref not in stored:
                problems.append(f"seq {entry['seq']}: artifact {ref} missing")
    if chain[0]["event_type"] != "StreamOpened":
        problems.append("seq 1 is not StreamOpened")
    decision = by_type["DecisionMade"]
    expected = recompute_decision(chain, section["artifacts"], section["derivation"])
    for member, value in expected.items():
        if decision["payload"][member] != value:
            problems.append(f"DecisionMade.{member}: {decision['payload'][member]!r} != recomputed {value!r}")
    intent = by_type["IntentProposed"]
    if intent["causation_id"] != decision["event_id"]:
        problems.append("IntentProposed.causation_id is not the DecisionMade")
    action = {k: decision["payload"][k] for k in intent["payload"]}
    if intent["payload"] != action:
        problems.append("IntentProposed does not repeat the DecisionMade's action")
    received = next(e["body"] for e in v3["chain"] if e["event_type"] == "IntentReceived")
    copied = {k: v for k, v in received["payload"].items() if k not in ("intent_id", "agent_id")}
    if intent["payload"] != copied:
        problems.append("IntentProposed differs from the IntentReceived vector less intent_id and agent_id")
    if (
        received["payload"]["intent_id"] != intent["event_id"]
        or received["causation_id"] != intent["event_id"]
    ):
        problems.append("IntentReceived does not name the IntentProposed as its intent")
    if received["payload"]["agent_id"] != intent["stream_id"].split(":")[2]:
        problems.append("IntentReceived.agent_id is not the agent stream's agent")
    if not intent["recorded_at"] < received["recorded_at"]:
        problems.append("IntentProposed must be recorded before the account stream copies it")
    mode, switch = by_type["AgentModeChanged"], by_type["KillSwitchActivated"]
    if switch["payload"]["mode_event"] != mode["event_id"] or mode["payload"]["reason"] != "kill_switch":
        problems.append("KillSwitchActivated.mode_event does not name its AgentModeChanged")
    if mode["payload"]["to"] != "stopped":
        problems.append("an owner kill switch's final mode is stopped (trading spec §5.5)")
    owner = by_type["OwnerExitRequested"]["payload"]
    derivation = section["derivation"]
    if owner["bid"] != derivation["owner_bid"] or dec(owner["floor"]) != dec(derivation["owner_bid"]) * (
        1 - dec(derivation["max_exit_offset"])
    ):
        problems.append("OwnerExitRequested.floor is not the default floor of its confirmed bid")
    for case in section["invalid_drafts"]:
        got = violations(apply_changes(chain, case))
        want = case["expect"]
        if len(got) != 1 or (got[0].reason, got[0].path) != (want["reason"], want["path"]):
            problems.append(f"{case['name']}: expected exactly {want['reason']} at {want['path']}, got {got}")
    for entry in chain:
        got = violations(draft_of(entry["body"]))
        if got:
            problems.append(f"seq {entry['seq']}: valid event breaks {got}")
    return problems


