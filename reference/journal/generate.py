def hash_chain(bodies: list[dict], genesis: str) -> list[dict]:
    entries, prev = [], genesis
    for body in bodies:
        body["prev_hash"] = prev
        text = canon(body)
        prev = sha256_hex(text.encode())
        entries.append(
            {
                "seq": body["seq"],
                "event_type": body["event_type"],
                "body": body,
                "canonical": text,
                "hash": prev,
            }
        )
    return entries


def draft_of(body: dict) -> dict:
    return {k: copy.deepcopy(v) for k, v in body.items() if k not in JOURNAL_FIELDS}


def set_path(draft: dict, path: str, value) -> None:
    *parents, last = path.split(".")
    node = draft
    for name in parents:
        node = node[name]
    node[last] = copy.deepcopy(value)


