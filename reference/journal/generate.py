@dataclass(frozen=True)
class Violation:
    rule: str
    reason: str
    path: str


def type_violations(ty: T, value, path: str, skip: frozenset[str]) -> list[Violation]:
    """Every type violation, in the order the journal reports them: extra members first (in key
    order), then the declared members in declaration order."""

    def bad(reason: str, rule: str = "types") -> list[Violation]:
        return [Violation(rule, reason, path)]

    kind = ty.kind
    if kind == "nullable":
        return [] if value is None else type_violations(ty.inner, value, path, skip)
    if kind == "record":
        if not isinstance(value, dict):
            return bad("schema")
        names = [name for name, _ in ty.fields]
        out = []
        if "record.extra" not in skip:
            out += [
                Violation("record.extra", "schema", f"{path}.{k}".lstrip("."))
                for k in sorted(value)
                if k not in names
            ]
        for name, inner in ty.fields:
            member = f"{path}.{name}".lstrip(".")
            if name not in value:
                out.append(Violation("record.missing", "schema", member))
            else:
                out += type_violations(inner, value[name], member, skip)
        return out
    if kind == "list":
        if not isinstance(value, list):
            return bad("schema")
        return [
            v for i, item in enumerate(value) for v in type_violations(ty.inner, item, f"{path}[{i}]", skip)
        ]
    if kind == "object":
        return [] if isinstance(value, dict) else bad("schema")
    if kind == "int":
        ok = isinstance(value, int) and not isinstance(value, bool) and 0 <= value <= MAX_INT
        return [] if ok else bad("schema")
    if kind == "bool":
        return [] if isinstance(value, bool) else bad("schema")
    if not isinstance(value, str):
        return bad("schema")
    checks = {
        "str": lambda s: s != "" or "types.str_nonempty" in skip,
        "id": lambda s: bool(IDENT.match(s)),
        "ulid": is_ulid,
        "dec": lambda s: normalize_decimal(s) is not None,
        "ts": lambda s: is_timestamp(s) or "types.timestamp" in skip,
        "ref": lambda s: bool(DIGEST.match(s)),
        "one_of": lambda s: s in ty.options,
    }
    return [] if checks[kind](value) else bad("non_canonical")


def digest_strings(value) -> set[str]:
    match value:
        case str() if DIGEST.match(value):
            return {value}
        case list():
            return set().union(*(digest_strings(v) for v in value)) if value else set()
        case dict():
            return set().union(*(digest_strings(v) for v in value.values())) if value else set()
    return set()


def ascending(items: list) -> bool:
    """Strictly ascending, so a repeat is refused as well as a swap."""
    return all(a < b for a, b in itertools.pairwise(items))


def strictness(mode: str) -> int:
    return MODES.index(mode)


def consistency_violations(event_type: str, draft: dict, skip: frozenset[str]) -> list[Violation]:
    """The §9.1 consistency rules, evaluated only on a well-typed payload, each reported once."""
    p = draft["payload"]
    out: list[Violation] = []

    def rule(number: int, holds: bool, reason: str, path: str) -> None:
        name = f"rule.{number}"
        if not holds and name not in skip:
            out.append(Violation(name, reason, path))

    if event_type in ("DecisionMade", "IntentProposed"):
        adds_risk = p["purpose"] in RISK_ADDING
        rule(1, (p["side"] == "buy") == adds_risk, "schema", "payload.side")
        priced = p["limit_price"] is not None
        rule(2, priced == (p["type"] == "limit"), "schema", "payload.limit_price")
        rule(3, p["type"] != "market" or not adds_risk, "schema", "payload.type")
    if event_type == "DecisionMade":
        allow = p["dry_run"] == "allow"
        rule(4, (p["reason_code"] is None) == allow, "schema", "payload.reason_code")
        rule(5, (p["autonomy"] is not None) == allow, "schema", "payload.autonomy")
        rule(6, p["dry_run"] != "defer" or p["purpose"] == "discretionary_exit", "schema", "payload.dry_run")
        rule(7, p["autonomy"] in (None, "auto") or p["purpose"] in RISK_ADDING, "schema", "payload.autonomy")
        risk_exit = p["purpose"] == "risk_exit"
        wrong = [
            m for m in ("exit_conviction", "buy_conviction", "combined_score") if (p[m] is None) != risk_exit
        ]
        rule(8, not wrong, "schema", f"payload.{wrong[0]}" if wrong else "")
        rule(9, ascending(p["outputs_used"]), "non_canonical", "payload.outputs_used")
        keys = [w["key"].encode() for w in p["model_weights"]]
        rule(9, ascending(keys), "non_canonical", "payload.model_weights")
        order = [CLIPS.index(c) for c in p["clips_applied"]]
        rule(9, ascending(order), "non_canonical", "payload.clips_applied")
    if event_type == "IntentProposed":
        rule(10, draft["causation_id"] is not None, "schema", "causation_id")
    if event_type == "AgentModeChanged":
        rule(11, strictness(p["to"]) >= strictness(p["lifecycle"]), "schema", "payload.to")
    if event_type == "OwnerExitRequested":
        members = ("bid", "bid_size", "floor", "user", "step_up")
        wrong = [m for m in members if (p[m] is not None) != p["confirmed"]]
        rule(12, not wrong, "schema", f"payload.{wrong[0]}" if wrong else "")
    if event_type == "ModelOutputRecorded" and (p["thesis_id"] is None) != (p["lineage_id"] is None):
        rule(13, False, "schema", "payload.thesis_id" if p["thesis_id"] is None else "payload.lineage_id")
    return out


def subject_violations(event_type: str, draft: dict, skip: frozenset[str]) -> list[Violation]:
    """Rules 14 and 15: a payload that names a subject names this stream's (reason `stream_mismatch`)."""
    _, workspace, agent = draft["stream_id"].split(":")
    p = draft["payload"]
    out = []
    opened = f"agent:{p.get('workspace_id')}:{p.get('agent_id')}"
    if event_type == "StreamOpened" and "rule.14" not in skip and opened != draft["stream_id"]:
        out.append(Violation("rule.14", "stream_mismatch", "stream_id"))
    if event_type in ("KillSwitchActivated", "OwnerExitRequested"):
        expected = {"agent": agent, "workspace": workspace}.get(p["scope"])
        if expected is not None and p["subject"] != expected and f"rule.15.{p['scope']}" not in skip:
            out.append(Violation(f"rule.15.{p['scope']}", "stream_mismatch", "payload.subject"))
    return out


def violations(draft: dict, skip: frozenset[str] = frozenset()) -> list[Violation]:
    """Every rule an agent-stream draft breaks, in the journal's check order (spec §9.1)."""
    out = type_violations(ENVELOPE, draft, "", skip)
    if out:
        return out
    if draft["envelope_version"] != 1:
        return [Violation("envelope", "schema", "envelope_version")]
    event_type = draft["event_type"]
    stream = draft["stream_id"].split(":")
    if event_type not in REQUIRED_REFS:
        return [Violation("catalogue", "unknown_event_type", "event_type")]
    if len(stream) != 3 or not all(IDENT.match(s) for s in stream):
        return [Violation("stream", "non_canonical", "stream_id")]
    if stream[0] != "agent":
        return [Violation("stream", "wrong_stream", "event_type")]
    if draft["actor"]["kind"] in ("system", "agent") and draft["actor"]["build"] is None:
        out.append(Violation("actor", "schema", "actor.build"))
    refs = draft["config_refs"]
    for kind in sorted(refs):
        if kind not in CONFIG_REF_KINDS:
            out.append(Violation("config_refs", "schema", f"config_refs.{kind}"))
        elif not (isinstance(refs[kind], str) and DIGEST.match(refs[kind])):
            out.append(Violation("config_refs", "non_canonical", f"config_refs.{kind}"))
    if "config_refs.required" not in skip:
        missing = [k for k in REQUIRED_REFS[event_type] if k not in refs]
        out += [
            Violation("config_refs.required", "missing_config_ref", f"config_refs.{k}") for k in missing[:1]
        ]
    if draft["schema_version"] != 1:
        return [*out, Violation("catalogue", "unknown_schema", "payload")]
    payload_types = type_violations(SCHEMAS[("agent", event_type)], draft["payload"], "payload", skip)
    out += payload_types
    if not payload_types:
        out += consistency_violations(event_type, draft, skip)
    if "artifact_refs" not in skip and draft["artifact_refs"] != sorted(digest_strings(draft["payload"])):
        out.append(Violation("artifact_refs", "artifact_refs", "artifact_refs"))
    if not ascending(draft["pii_refs"]):
        out.append(Violation("pii_refs", "pii_refs", "pii_refs"))
    if not payload_types:
        out += subject_violations(event_type, draft, skip)
    return out


