# --------------------------------------------------------------------------- self-test on version 3


def self_test(v3: dict) -> None:
    """The canonicalizer reproduces every version-3 vector before anything it produces is trusted."""
    for entry in v3["chain"]:
        text = canon(entry["body"])
        assert text == entry["canonical"], f"v3 seq {entry['seq']}: canonical differs"
        assert sha256_hex(text.encode()) == entry["hash"], f"v3 seq {entry['seq']}: hash differs"
    first = v3["chain"][0]
    assert canon({"body": first["body"], "hash": first["hash"]}) == v3["export_line_seq_1"]
    escaping = v3["string_escaping"]
    data = canon_bytes(escaping["object"])
    assert data.hex() == escaping["canonical_utf8_hex"], "v3 string escaping differs"
    assert sha256_hex(data) == escaping["hash"]
    for case in v3["decimal_normalization"]["accept"]:
        assert normalize_decimal(str(case["input"])) == case["canonical"], case
    for rejected in v3["decimal_normalization"]["reject"]:
        assert normalize_decimal(str(rejected)) is None, rejected


